#include <stdio.h>
#include <stdint.h>
#include "aes8.h"

int main()
{

    // 파라미터
    uint8_t a[16] = {0x32, 0x43, 0xf6, 0xa8, 0x88, 0x5a, 0x30, 0x8d, 0x31, 0x31, 0x98, 0xa2, 0xe0, 0x37, 0x07, 0x34};
    uint8_t k[16] = {0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c};
    // 파라미터

    encrypt8(k, a);
    printf("ciphertext \n");

    for (int j = 0; j < 16; j++)
        printf("%02x", a[j]);
    printf("\n");

    decrypt8(k, a);
    printf("ciphertext \n");

    for (int j = 0; j < 16; j++)
        printf("%02x", a[j]);
    printf("\n");

    return 0;
}
