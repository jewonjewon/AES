void show8(uint8_t *a)
{
    printf("block: ");
    for (int j = 0; j < 16; j++)
        printf("%02x", a[j]);
    printf("\n");
}

void wordToByte(uint32_t *input, uint8_t *output, uint8_t wordnum)
{
    for (int j = 0; j < (4 * wordnum); j++)
        output[j] = ((input[j / 4] >> (24 - ((j % 4) * 8)))) & 0xff;
}

